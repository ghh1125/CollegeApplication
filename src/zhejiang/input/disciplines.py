def category_of(code4: str) -> str:
    """4 位专业类码 → 门类名。"""
    return CATEGORY_NAMES.get(str(code4)[:2], "其他")


def class_name(code4: str) -> str:
    """4 位专业类码 → 专业类名（无名时回退到代码）。"""
    return MAJOR_CLASS_NAMES.get(str(code4), str(code4))


def classes_grouped() -> dict[str, list[tuple[str, str]]]:
    """按门类分组的专业类列表：{门类名: [(code4, 专业类名), ...]}，供页面级联多选。"""
    grouped: dict[str, list[tuple[str, str]]] = {}
    for code4, name in MAJOR_CLASS_NAMES.items():
        grouped.setdefault(CATEGORY_NAMES.get(code4[:2], "其他"), []).append((code4, name))
    for cat in grouped:
        grouped[cat].sort()
    return grouped
