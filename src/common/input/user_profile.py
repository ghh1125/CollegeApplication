"""模块①：用户画像 / 选专业风格对话（省份无关，可复用）。

与「填报顾问」(llm.chat_with_advisor) 分开：
  - 本模块只聊兴趣、性格、学科偏好、职业倾向，帮还没想好的考生**找专业方向**。
  - 只给「建议参考」，不收集位次/选科，也不输出 JSON、不自动填表。
  - 用户看完建议后，仍需自己到「目标输入」模块手动填写。
"""

from __future__ import annotations

from src.common.input.llm import _stream

WELCOME = (
    "没关系，很多人这会儿都没想好 👌 我先陪你聊几句，帮你找几个**可能适合的专业方向**。\n\n"
    "随便聊就行，比如：\n"
    "- 你平时对什么最感兴趣？（游戏、数码、商业、画画、医学、动物、写作…）\n"
    "- 高中哪几门课学得相对带劲、哪几门头疼？\n"
    "- 你更喜欢一个人钻研，还是和人打交道？\n"
    "- 以后更看重赚钱、稳定，还是做喜欢的事？\n\n"
    "想到啥说啥，我会一边聊一边给你推荐方向。聊得差不多了，点下面「我想好了，去填志愿信息」即可。\n\n"
    "*这些只是参考建议，最终读什么由你自己决定。*"
)

_SYSTEM = (
    "你叫小明，是高考选专业的兴趣引导顾问。当前任务：通过轻松对话了解考生的兴趣、性格、"
    "学科偏好和职业倾向，帮还没想好的学生**找到 2-3 个适合的专业方向**。\n"
    "规则：\n"
    "- 每次只问 1-2 个问题，像聊天一样，不要一次抛一堆。\n"
    "- 聊到能判断时，就给出 2-3 个推荐专业方向，每个一句话说清「为什么适合你」+「大致就业去向」。\n"
    "- 用就业倒推法：说中等毕业生的真实去向和薪资区间，不说「前景好」这类空话。\n"
    "- 给建议时诚实提醒：这只是参考方向，具体专业冷热、是否适合还要本人权衡。\n"
    "- **不要**询问或收集位次、选考科目、分数——那是下一步「填志愿信息」做的事。\n"
    "- **不要**输出任何 JSON 或表格代码块；只用自然语言给建议。\n"
    "- 回复控制在 200 字以内。"
)


def chat_user_profile(messages: list[dict], api_key: str | None = None):
    """流式返回兴趣引导对话（模块①）。messages 为对话历史（不含 system）。"""
    return _stream([{"role": "system", "content": _SYSTEM}] + messages, api_key=api_key)
